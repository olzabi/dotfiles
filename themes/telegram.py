#!/usr/bin/env python3
"""Telegram Desktop darkvoid + dim-light themes, generated from Telegram's own Night palette.

  Called by themes/build: dark/telegram.night-palette -> dark/ and light/telegram.tdesktop-theme

dark/telegram.night-palette is tdesktop's Telegram/Resources/night.tdesktop-theme colours (every key Telegram knows).
Night -> darkvoid by role: blue-greys become darkvoid's neutral greys (same lightness order),
Telegram blue becomes the sage accent, other hues keep their hue with chroma capped (no neon).
darkvoid -> light goes through themes/darkvoid-light.py like every other app.
"""
import importlib.util, io, pathlib, re, sys, zipfile

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('dl', here / 'darkvoid-light.py')
dl = importlib.util.module_from_spec(spec); spec.loader.exec_module(dl)

NIGHT_BG, DV_BG, DV_TOP = '#17212b', '#1c1c1c', '#d1d1d1'   # night window bg; darkvoid bg; brightest text
ACCENT = dl.oklch('#83b7ad')                                   # house sage
L0, L1, LTOP = dl.oklch(NIGHT_BG)[0], dl.oklch(DV_BG)[0], dl.oklch(DV_TOP)[0]

def to_dark(h):
    if h.lower() == '#000000': return h
    L, C, H = dl.oklch(h)
    Lo = L1 + (L - L0) * (LTOP - L1) / (1 - L0) if L >= L0 else L * L1 / L0   # night bg -> 1c1c1c, white -> d1d1d1
    if C < 0.045: return dl.from_oklch(Lo, 0, 0)                               # blue-grey -> neutral grey
    cap = 0.035 if Lo < 0.45 else 0.1                                           # dark fills stay quiet tints
    if 200 <= H <= 275: return dl.from_oklch(Lo, min(C, ACCENT[1], cap), ACCENT[2])  # telegram blue -> sage
    return dl.from_oklch(Lo, min(C, cap), H)                                    # other hues, de-neoned

HEX = re.compile(r'#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b')
def convert(text, f): return HEX.sub(lambda m: f('#' + m[1]) + (m[2] or ''), text)

LINE = re.compile(r'^([A-Za-z0-9_]+)(\s*:\s*)#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?', re.M)
def to_light_keyed(text):
    """dark -> light, but coloured backgrounds (keys with Bg) always become pale fills, so text drawn on
    them (converted to dark ink) stays readable; the plain converter would turn bright fills into dark ink."""
    def one(m):
        h, a = '#' + m[3], m[4] or ''
        _, C, H = dl.oklch(h)
        if 'Bg' in m[1] and C >= 0.015 and dl.contrast(h, dl.DARK_BG) >= 1.6:
            out = dl._darker(min(C, 0.06), H, 1.3)
        else:
            out = dl.to_light(h)
        return m[1] + m[2] + out + a
    return LINE.sub(one, text)

def write(path, colors, bg):
    png = io.BytesIO()
    import struct, zlib
    raw = b'\x00' + bytes.fromhex(bg[1:])
    chunk = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d))
    png.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 1, 1, 8, 2, 0, 0, 0))
              + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as z:
        for name, data in (('colors.tdesktop-theme', colors), ('background.png', png.getvalue())):  # flat chat bg
            z.writestr(zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0)), data, zipfile.ZIP_DEFLATED)  # fixed date: same input, same file

def main(src, root):
    night = pathlib.Path(src).read_text()
    dark = convert(night, to_dark)
    light = to_light_keyed(dark)
    root = pathlib.Path(root)
    write(root / 'dark/telegram.tdesktop-theme', '// darkvoid, generated by themes/build from telegram.night-palette\n' + dark, '#161616')
    write(root / 'light/telegram.tdesktop-theme', '// darkvoid dim-light, generated by themes/build\n' + light,
          dl.to_light('#161616'))
    return dark, light

